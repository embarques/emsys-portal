import type { ApiBranchDtoPayload } from "@/lib/api/payloads";
import type { RouteCrewRole } from "@/lib/route-manager/types";

import type {
  ActiveRouteBranchRef,
  ActiveRouteContainerRef,
  RouteType,
} from "./types";

/** Employee ref on vehicle route read/write payloads. */
export type VehicleRouteEmployeeRef = {
  id: number;
  name: string;
  role?: RouteCrewRole;
};

/** Crew member on a vehicle route write payload. */
export type VehicleRouteEmployeeWriteRef = VehicleRouteEmployeeRef & {
  role: RouteCrewRole;
};

/** Container reference for delivery vehicle routes. */
export type VehicleRouteContainerWriteRef = {
  id: number;
  number: string;
};

/**
 * `POST/PUT /v1/vehicle-routes` write body.
 *
 * - `date` is required; recurring weekdays are not part of a daily route.
 * - `routeType` is the only route type field (legacy `type` is not sent).
 * - `driver` and `supervisor` are required and may be the same employee;
 *   `helpers` hold only the helper role.
 * - `container` is required for delivery, forbidden for pickup.
 * - `name` is generated by the server (`YYYY-MM-DD_Vehicle_Supervisor+Employee+…`)
 *   and omitted on create and update.
 * - No route crew reference: a crew only prefills employees in the form.
 * - Audit fields are server-set and never sent.
 */
export type VehicleRouteWritePayload = {
  routeType: RouteType;
  active: boolean;
  branch: ApiBranchDtoPayload;
  employees: VehicleRouteEmployeeWriteRef[];
  driver: VehicleRouteEmployeeRef;
  supervisor: VehicleRouteEmployeeRef;
  helpers: VehicleRouteEmployeeRef[];
  date: string;
  container?: VehicleRouteContainerWriteRef;
  vehicle?: { id: string; name: string; branch?: string };
  rate?: number;
};

/** `GET /v1/vehicle-routes` record (normalized shape lives in `types.ts`). */
export type VehicleRouteRecord = {
  id: string;
  name: string;
  routeType: RouteType;
  active: boolean;
  branch: ActiveRouteBranchRef | null;
  container: ActiveRouteContainerRef | null;
  date: string;
  employees: VehicleRouteEmployeeWriteRef[];
  createdAt: string;
  createdBy: string;
  updatedAt: string;
  updatedBy: string;
  rate?: number;
};

/** Example `POST /v1/vehicle-routes` pickup body (date-based). */
export const PICKUP_VEHICLE_ROUTE_WRITE_EXAMPLE = {
  routeType: "pickup",
  active: true,
  branch: { id: 1, code: "NY", name: "Embarque Tenares" },
  date: "2026-07-03T08:00:00Z",
  driver: { id: 5, name: "Jane Driver" },
  supervisor: { id: 5, name: "Jane Driver" },
  helpers: [{ id: 6, name: "Sam Helper" }],
  employees: [
    { id: 5, name: "Jane Driver", role: "driver" },
    { id: 6, name: "Sam Helper", role: "helper" },
  ],
} as const satisfies VehicleRouteWritePayload;

